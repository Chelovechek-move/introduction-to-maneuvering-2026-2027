#!/usr/bin/env python3
"""Slide versions of the saved lecture-8 example; no orbit recomputation.

Run from the repository root: python3 8/images/slides_figures_example.py
The numerical source is kepler-results.npz/json, generated by kepler_transfer.py.
Only the panel arrangement and the established lecture-7 graphic style change.
"""
from pathlib import Path
import json
import os

HERE = Path(__file__).resolve().parent
BUILD = HERE.parent / "build"
BUILD.mkdir(exist_ok=True)
PREVIEWS = BUILD / "slides-figures"
PREVIEWS.mkdir(exist_ok=True)
os.environ.setdefault("MPLCONFIGDIR", str(BUILD / "mplconfig-slides"))

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib import font_manager
from matplotlib.ticker import MaxNLocator
import numpy as np

PAPER, INK = "#FBF9F3", "#302B28"
BLUE, GREEN, ORANGE, PURPLE = "#187AA5", "#087F78", "#B57714", "#79539C"
for font in sorted(Path("/usr/share/fonts/truetype/paratype").glob("PTF*.ttf")):
    font_manager.fontManager.addfont(str(font))
plt.rcParams.update({
    "font.family": "PT Serif", "font.size": 10,
    "mathtext.fontset": "custom", "mathtext.rm": "PT Serif",
    "mathtext.it": "PT Serif:italic", "mathtext.bf": "PT Serif:bold",
    "mathtext.fallback": "cm", "axes.labelsize": 10,
    "axes.titlesize": 11, "legend.fontsize": 8.5,
    "xtick.labelsize": 9, "ytick.labelsize": 9,
    "axes.spines.top": False, "axes.spines.right": False,
    "axes.edgecolor": INK, "text.color": INK, "axes.labelcolor": INK,
    "xtick.color": INK, "ytick.color": INK,
    "figure.facecolor": PAPER, "axes.facecolor": PAPER,
    "savefig.facecolor": PAPER, "pdf.fonttype": 42,
})

RESULT = json.loads((HERE / "kepler-results.json").read_text())
DATA = np.load(HERE / "kepler-results.npz")
STAGES = [
    ("finite_central", "Центральное поле", BLUE, "-"),
    ("finite_j2", "Исходные, $J_2$", ORANGE, "--"),
    ("targeted_j2", "Уточнённые, $J_2$", GREEN, "-"),
]


def finish(fig, name):
    fig.savefig(HERE / (name + "-slide.pdf"), bbox_inches="tight", pad_inches=.035)
    fig.savefig(PREVIEWS / (name + "-slide.png"), dpi=170, bbox_inches="tight", pad_inches=.035)
    plt.close(fig)


def grid(ax):
    ax.grid(color="#A9CADA", linewidth=.55, alpha=.6)
    ax.set_axisbelow(True)


def elements(rows, name, figsize):
    fig, axes = plt.subplots(1, len(rows), figsize=figsize)
    targets = [42164 / 1000, .05, 3., 30., 0.]
    labels = ["$a$, тыс. км", "$e$", "$i$, град", r"$\Omega$, град", r"$\omega$, град"]
    for ax, row in zip(axes, rows):
        for stage, label, color, style in STAGES:
            t, z = DATA[stage + "_t"], DATA[stage + "_z"]
            ordinate = z[row].copy()
            if row == 0:
                ordinate /= 1000
            elif row >= 2:
                ordinate = np.rad2deg(ordinate)
            ax.plot(t / 86400, ordinate, color=color, ls=style, lw=1.35, label=label)
        ax.axhline(targets[row], color="#6D6560", ls=":", lw=1.)
        ax.set(xlim=(0, 10), xlabel="Время, сут", title=labels[row])
        ax.xaxis.set_major_locator(MaxNLocator(4, integer=True))
        ax.yaxis.set_major_locator(MaxNLocator(5))
        if row == 1:
            ax.set_ylim(0, .72)
        grid(ax)
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper center", ncol=3, frameon=False,
               bbox_to_anchor=(.5, 1.01), columnspacing=1.1, handlelength=2.5)
    fig.tight_layout(w_pad=1., rect=(0, 0, 1, .90))
    finish(fig, name)


def elements_stacked():
    """Align all five elements in time on one slide, using the saved data."""
    fig, axes = plt.subplots(5, 1, figsize=(6.5, 3.45), sharex=True)
    targets = [42164 / 1000, .05, 3., 30., 0.]
    labels = ["$a$\nтыс. км", "$e$", "$i$\nград", r"$\Omega$" + "\nград",
              r"$\omega$" + "\nград"]
    ticks = [[18, 30, 42], [0, .3, .6], [3, 5, 7], [24, 27, 30], [0, 6, 12]]
    for row, ax in enumerate(axes):
        for stage, label, color, style in STAGES:
            t, z = DATA[stage + "_t"], DATA[stage + "_z"]
            ordinate = z[row].copy()
            if row == 0:
                ordinate /= 1000
            elif row >= 2:
                ordinate = np.rad2deg(ordinate)
            ax.plot(t / 86400, ordinate, color=color, ls=style, lw=1.35,
                    label=label)
        ax.axhline(targets[row], color="#6D6560", ls=":", lw=1.,
                   label=r"Цель в $t_f$")
        ax.set_yticks(ticks[row])
        ax.set_ylabel(labels[row], rotation=0, ha="right", va="center",
                      labelpad=13, fontsize=10.5, linespacing=.95)
        ax.yaxis.set_label_coords(-.085, .5)
        ax.tick_params(axis="y", labelsize=9.5, pad=3, length=2.5)
        ax.tick_params(axis="x", labelsize=9.5, length=0 if row < 4 else 2.5)
        ax.margins(y=.09)
        grid(ax)
    axes[-1].set(xlim=(0, 10), xticks=[0, 2, 4, 6, 8, 10])
    axes[-1].set_xlabel("Время, сут", fontsize=10, labelpad=2)
    handles, legend_labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, legend_labels, loc="upper center", ncol=4,
               frameon=False, bbox_to_anchor=(.53, 1.005),
               fontsize=9.5, columnspacing=1., handlelength=2.)
    fig.subplots_adjust(left=.15, right=.985, top=.91, bottom=.105,
                        hspace=.26)
    finish(fig, "kepler-elements-stacked")


def groups():
    fig, axes = plt.subplots(1, 2, figsize=(6.5, 2.25))
    for ax, start, end, color in [(axes[0], 0, 3, BLUE), (axes[1], 3, 7, PURPLE)]:
        subset = RESULT["nominal_burns"][start:end]
        values = [b["delta_v_mps"] for b in subset]
        ax.bar(range(len(subset)), values, color=color, width=.52)
        for j, burn in enumerate(subset):
            label = (f"{burn['delta_v_mps']:.1f}\n{burn['duration_s']/60:.2f} мин").replace(".", ",")
            ax.annotate(label, (j, values[j]), xytext=(0, 4), textcoords="offset points",
                        ha="center", fontsize=9)
        ax.set_xticks(range(len(subset)), [str(j) for j in range(start + 1, end + 1)])
        ax.set(xlabel="Номер манёвра", ylabel=r"$\Delta V_j$, м/с", ylim=(0, max(values) * 1.58))
        ax.yaxis.set_major_locator(MaxNLocator(4))
        grid(ax)
        ax.grid(axis="x", visible=False)
    axes[0].set_title("Перигейная группа")
    axes[1].set_title("Апогейная группа")
    fig.tight_layout(w_pad=1.5)
    finish(fig, "kepler-groups")


def convergence():
    hist = RESULT["targeting_history"]
    fig, ax = plt.subplots(figsize=(3.05, 2.75))
    ax.semilogy([h["iteration"] for h in hist], [h["norm"] for h in hist],
                "o-", color=BLUE, ms=4, lw=1.4)
    ax.axhline(RESULT["epsilon"], color="#6D6560", ls="--", lw=1., label=r"$\varepsilon=10^{-8}$")
    ax.set(xlabel="Номер итерации", ylabel=r"$\|\mathbf{F}\|_2$", ylim=(1e-15, 1.), xticks=range(5))
    ax.set_yticks([1, 1e-4, 1e-8, 1e-12])
    ax.legend(frameon=False, loc="upper right", fontsize=9)
    grid(ax)
    fig.tight_layout()
    finish(fig, "kepler-convergence")


def timeline():
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(6.4, 2.7), sharex=True,
                                  gridspec_kw={"height_ratios": [.65, 1.35]})
    t = DATA["targeted_j2_t"] / 86400
    ax1.plot(t, 450 * DATA["targeted_j2_active"], color=BLUE, lw=1.1)
    ax1.set(ylabel="Тяга, Н", ylim=(-25, 585), yticks=[0, 450])
    for j, burn in enumerate(RESULT["targeted_burns"]):
        ax1.annotate(str(j + 1), (burn["center_s"] / 86400, 450),
                     xytext=(0, 4), textcoords="offset points", ha="center", fontsize=9)
    ax2.plot(t, DATA["targeted_j2_z"][6], color=GREEN, lw=1.5, label="Масса КА")
    ax2.axhline(1075, color="#C44847", ls="--", lw=1., label="Сухая масса 1075 кг")
    ax2.set(ylabel="Масса, кг", xlabel="Время, сут", xlim=(0, 10), ylim=(1035, 2050))
    ax2.set_yticks([1100, 1400, 1700, 2000])
    ax2.legend(frameon=False, loc="upper right", fontsize=8.5)
    for ax in [ax1, ax2]:
        grid(ax)
    fig.tight_layout(h_pad=.12)
    finish(fig, "kepler-timeline")


if __name__ == "__main__":
    elements_stacked()
    elements([0, 1, 2], "kepler-elements-aei", (6.65, 2.45))
    elements([3, 4], "kepler-elements-angles", (6.35, 2.45))
    groups()
    convergence()
    timeline()
